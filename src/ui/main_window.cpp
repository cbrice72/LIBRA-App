/**
 * @brief Standard constructor.
 *
 * @param parent Owning Qt widget (default: nullptr)
 */
MainWindow::MainWindow(QWidget* parent)
    : QMainWindow(parent),
      ui_(new Ui::MainWindow),
      ser_water_(new QSerialPort(this)),
      ser_servo_(new QSerialPort(this)) {
    ui_->setupUi(this);
    this->setMinimumSize(this->minimumSizeHint());  // enforce minimum size

    // Runtime checks
    CheckWslEnvironment();

    // GUI configuration
    ConfigureUi();
    InitializeThreads();
    InitializeFeedbackElementMap();

    // Component auto-connect
    auto reply = QMessageBox::question(nullptr, "LIBRA App Startup",
                                       "Automatically connect all components?",
                                       QMessageBox::Yes | QMessageBox::No);
    if (reply == QMessageBox::Yes) {
        ui_->a_connect_all->trigger();
    }
}

/**
 * @brief Standard destructor.
 */
MainWindow::~MainWindow() {
    // Wrap up the worker thread(s) gracefully
    if (log_thread_ != nullptr && log_thread_->isRunning()) {
        log_thread_->requestInterruption();  // signal thread to stop looping
        log_thread_->wait();  // wait for thread cleanup to finish
    }

#if LIBRA_VERSION == 2
    if (epos_thread_ != nullptr && epos_thread_->isRunning()) {
        epos_thread_->requestInterruption();
        epos_thread_->wait();
    }
#endif

    if (hebi_thread_ != nullptr && hebi_thread_->isRunning()) {
        hebi_thread_->requestInterruption();
        hebi_thread_->wait();
    }

    delete ui_;
}

