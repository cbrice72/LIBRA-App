#if LIBRA_VERSION == 2
/**
 * @brief Event handler for "Actuators/EPOS" menu action "Connect".
 *        Opens a dialog allowing the user to select connection settings.
 */
void MainWindow::on_a_epos_connect_triggered() {
    // Native Linux should have no issues connecting with defaults
    if (!ui_->a_epos_usedefaults->isChecked() || util::IsWslEnvironment()) {
        // Prompt user to select an EPOS device
        OpenEposDialog dialog(this);

        if (dialog.exec() == QDialog::Accepted) {
            auto params = dialog.GetDeviceParams();

            if (!params.is_set) {
                logger_->Warn("Parameter selection incomplete");
                return;
            }

            if (util::IsWslEnvironment()) {
                // What the EPOS API retrieves as "USB#" on WSL is actually
                // "hidraw#", so we modify the port name here
                if (auto pos = params.port_name.find("USB");
                    pos != std::string::npos) {
                    params.port_name.replace(pos, 3, "/dev/hidraw");
                    logger_->Info("WSL detected - modified EPOS port name to "
                                  + params.port_name);
                }
            }

            // Send selected device params to EposThread
            epos_thread_->SetDeviceParams(params.device_name,
                                          params.protocol_name,
                                          params.interface_name,
                                          params.port_name, params.baud_rate);
        } else {
            logger_->Debug("Parameter selection cancelled by user");
            return;
        }
    }

    emit ConnectEpos();
}
#endif

