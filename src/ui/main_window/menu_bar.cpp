/**
 * @brief Queries a serial device for its ID by sending a single "?" character.
 *
 * @param port_info Serial port to query
 * @param baud_rate Baud rate to use
 */
QString QueryDeviceId(const QSerialPortInfo& port_info,
                      const qint32& baud_rate = QSerialPort::Baud115200) {
    constexpr int kMaxRetries = 3;
    constexpr int kRetryDelayMs = 100;

    constexpr int kWriteTimeoutMs = 1000;
    constexpr int kReadTimeoutMs = 500;
    constexpr int kMaxLinesToRead = 3;  // prevent infinite loop on telemetry

    // Open a connection
    QSerialPort port;
    port.setPort(port_info);
    port.setBaudRate(baud_rate);
    port.setDataBits(QSerialPort::Data8);
    port.setParity(QSerialPort::NoParity);
    port.setStopBits(QSerialPort::OneStop);
    port.setFlowControl(QSerialPort::NoFlowControl);

    if (!port.open(QIODevice::ReadWrite)) {
        return {};  // failed to open port
    }

    QByteArray response;
    for (int i = 0; i < kMaxRetries; ++i) {
        // Attempt to query the device ID
        port.write("?");
        if (!port.waitForBytesWritten(kWriteTimeoutMs)) {
            // Failed to write to port, try again after a short delay
            QThread::msleep(kRetryDelayMs);
            continue;
        }

        // Read the response
        int lines_read = 0;
        while (port.waitForReadyRead(kReadTimeoutMs)
               && lines_read < kMaxLinesToRead) {
            while (port.canReadLine()) {
                QByteArray line = port.readLine().trimmed();
                if (line.startsWith('?')) {
                    port.close();
                    return QString(line.mid(1)).trimmed();  // strip leading '?'
                }
                lines_read++;
            }
        }
    }

    port.close();
    return {};
}

/**
 * @brief Attempts to auto-detect a serial port matching the requested ID. If
 *        not found, opens a dialog for the user to select a port.
 *
 * @param expected_id Device ID to look for
 * @param dialog_label Label for the manual selection dialog
 * @param parent Owning Qt widget
 */
QString FindPortForDevice(const QString& expected_id,
                          const QString& dialog_label, QWidget* parent) {
    // Attempt to auto-detect device
    const auto available_ports = QSerialPortInfo::availablePorts();
    for (const auto& port_info : available_ports) {
        if (!port_info.description().isEmpty()
            && QueryDeviceId(port_info).compare(expected_id, Qt::CaseInsensitive)
                   == 0) {
            qDebug() << "Found device with ID:" << expected_id << "("
                     << port_info.portName() << ")";
            return port_info.portName();
        }
    }

    qDebug() << "Could not find device with ID:" << expected_id
             << "-- displaying manual selection dialog";

    // Prompt user to manually select a device
    OpenSerialDialog dialog(parent, dialog_label);
    if (dialog.exec() == QDialog::Accepted) {
        return dialog.GetSelectedPortName();
    }

    return {};
}

