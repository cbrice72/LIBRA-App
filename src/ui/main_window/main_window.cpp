/**
 * @brief Fully deletes a widget or layout from the user interface.
 *
 * @tparam T Any visual QObject type
 * @param element Widget or layout to remove
 */
template<typename T>
void RemoveUiElement(T*& element) {
    if (!element) {
        return;
    }

    // To avoid duplicating code, define this lambda capable of handling both
    // QWidgets and QLayouts (since they boil down to different QObjects)
    auto RemoveFromParentLayout = [](QObject* obj) {
        if (!obj) {
            return;
        }

        // All objects are eventually children of a QWidget, so this is allowed
        if (auto* p = qobject_cast<QWidget*>(obj->parent())) {
            if (auto* pl = p->layout()) {
                // We must explicitly cast since indexOf() does not take QObjects
                if (auto* w = qobject_cast<QWidget*>(obj)) {
                    if (int i = pl->indexOf(w); i >= 0) {
                        delete pl->takeAt(i);
                    }
                } else if (auto* l = qobject_cast<QLayout*>(obj)) {
                    if (int i = pl->indexOf(l); i >= 0) {
                        delete pl->takeAt(i);
                    }
                }
            }
        }
    };

    RemoveFromParentLayout(element);

    // Handle layouts
    if constexpr (std::is_base_of_v<QLayout, T>) {
        // Recursively delete all children
        while (QLayoutItem* item = element->takeAt(0)) {
            if (auto* w = item->widget()) {
                RemoveUiElement(w);
            } else if (auto* l = item->layout()) {
                RemoveUiElement(l);
            }
            delete item;
        }
    }

    // Mark for deletion to reclaim visual space
    element->deleteLater();
    element = nullptr;
}

/**
 * @brief Gets a motion mode's text color, based on how much of the CW control
 *        it automates.
 *
 * @param mode Motion mode
 */
const char* MotionModeColor(const Motion::MotionMode& mode) {
    switch (mode) {
        case Motion::MotionMode::kFeedbackOnly:
            return Color::kOrange;  // CW only reacts
#if LIBRA_VERSION == 2
        case Motion::MotionMode::kTandem:
            return Color::kGreen;  // CW predicts + reacts
        case Motion::MotionMode::kCwPrimary:
            return Color::kBlue;  // CW is main mover
#endif
        default:
            return Color::kRed;  // Manual: no automatic CW
    }
}

