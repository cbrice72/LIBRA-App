/**
 * @brief Sorts important actuator information into individual UI elements.
 *
 * @param feedbacks Unordered map of joint(s) and their corresponding feedback
 * @param feedback_type Type of primary feedback provided
 *
 * @note To improve ease of use, LIBRA-I arm actuator angles (J1, J2, J3) in the
 *       UI are shown relative to a forward-facing perspective directly behind
 *       the robot, where "0" is directly forward, and counterclockwise movement
 *       is considered "+" (positive).
 */
void MainWindow::HandleActuatorFeedback(
    const std::unordered_map<Joint::Name, double>& feedbacks,
    const Actuator::Feedback& feedback_type) {
    const bool initialize = populate_targets_
                            && (feedback_type == Actuator::Feedback::kActualPos);

    for (const auto& feedback : feedbacks) {
        const auto& joint = feedback.first;
        const auto& val = feedback.second;

        // Index into matching label using map-of-maps initialized in constructor
        try {
            feedback_element_map_.at(joint)
                .at(feedback_type)
                ->setText(QString::number(val, 'f', kPrecision));
        } catch (const std::out_of_range&) {
            logger_->Error(
                "No UI element mapped to joint " + Joint::NameEnumToString(joint)
                + " (" + std::to_string(static_cast<int>(joint))
                + ") and feedback type "
                + Actuator::FeedbackEnumToString(feedback_type) + " ("
                + std::to_string(static_cast<int>(feedback_type)) + ")");
        }

        // Initialize target spin boxes to actual position after a connect
        if (initialize) {
            const auto spin_box = target_spin_box_map_.find(joint);
            if (spin_box != target_spin_box_map_.end()) {
                spin_box->second->setValue(val);
            }
            populate_targets_ = false;
        }
    }
}

