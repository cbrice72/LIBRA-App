/**
 * @brief Sets up signal and slot connections to child threads and spins them up.
 *
 * @note In Qt, managing a subclassed QThread generally takes 4 steps:
 *         1) Create the QThread object as a child of MainWindow.
 *         2) Connect its signals/slots to send/receive data to/from MainWindow.
 *         3) Connect its exit signal to its own destruction slot.
 *         4) Spin it off.
 *       A continuously looping thread needs a fifth step:
 *         5) In the MainWindow destructor, interrupt or forcibly stop it.
 *
 * @note Only used in constructor; separate function for readability.
 */
void MainWindow::InitializeThreads() {
    // ========== HEBI Thread ==========

    // NOTE: This constructor automatically determines the actuator family and
    //       names based on the LIBRA_VERSION the app is built with
    hebi_thread_ = new HebiThread(this, debug_mode_);

    // MainWindow signals
    connect(this, &MainWindow::EnableDebugMode,  // update debug mode
            hebi_thread_, &HebiThread::SetDebugMode);

    connect(ui_->a_hebi_connect, &QAction::triggered,  // connect to HEBI
            hebi_thread_, &HebiThread::Connect);
    connect(ui_->a_hebi_disconnect, &QAction::triggered,  // disconnect HEBI
            hebi_thread_, &HebiThread::Disconnect);

    connect(this, &MainWindow::CommandHebi,  // update HEBI target(s)
            hebi_thread_, &HebiThread::SetTarget);
    connect(ui_->pb_arm_stop, &QPushButton::clicked,  // stop ALL actuators
            hebi_thread_, &HebiThread::Stop);

    connect(this, &MainWindow::LoadHebiGains,  // load new gains
            hebi_thread_, &HebiThread::LoadGains);
    connect(ui_->a_hebi_log_start, &QAction::triggered,  // start new hebilog
            hebi_thread_, &HebiThread::StartHebiLog);
    connect(ui_->a_hebi_log_stop, &QAction::triggered,  // stop current hebilog
            hebi_thread_, &HebiThread::StopHebiLog);

    connect(this, &MainWindow::EnableAutoTorqueComp,  // auto-balancing
            hebi_thread_, &HebiThread::EnableTorqueControl);
    connect(this, &MainWindow::UpdateHebiTorqueCompBounds,  // update limits
            hebi_thread_, &HebiThread::SetTorqueCompBounds);

#if LIBRA_VERSION == 2
    connect(this, &MainWindow::EnableCwPrimary,  // pick main pitch joint mover
            hebi_thread_, &HebiThread::EnableCwPrimaryMode);
    connect(this, &MainWindow::EnableFreeMode,  // stop commanding pitch joint
            hebi_thread_, &HebiThread::EnableFreeMode);
    connect(this, &MainWindow::EnableInertiaFeedforward,  // use inertia terms
            hebi_thread_, &HebiThread::EnableInertiaFeedforward);
    connect(this, &MainWindow::UpdateHebiHandoffBand,  // update hand-off band
            hebi_thread_, &HebiThread::SetHandoffBand);

    connect(this, &MainWindow::StartHebiLevelCal,  // calibrate: level
            hebi_thread_, &HebiThread::StartLevelCalibration);
    connect(this, &MainWindow::StartHebiTwoAngleCal,  // calibrate: two angles
            hebi_thread_, &HebiThread::StartTwoAngleCalibration);
    connect(this, &MainWindow::StartHebiFrictionCal,  // calibrate: friction
            hebi_thread_, &HebiThread::StartFrictionCalibration);
    connect(this, &MainWindow::CancelHebiCal,  // cancel calibration
            hebi_thread_, &HebiThread::CancelCalibration);
    connect(this, &MainWindow::SaveHebiCal,  // save calibration
            hebi_thread_, &HebiThread::SaveCalibration);
    connect(this, &MainWindow::LoadHebiCal,  // load calibration
            hebi_thread_, &HebiThread::LoadCalibration);

    connect(flow_controller_, &FlowController::ReportStatus,  // CW flow (İ)
            hebi_thread_, &HebiThread::UpdateCounterweightFlow);

    // TankWidget only emits on level changes, so send starting CW volume now
    connect(ui_->tw_water_level_A, &TankWidget::LevelChanged,  // CW volume
            hebi_thread_, [this](double) {
                hebi_thread_->UpdateCounterweightVolume(
                    ui_->tw_water_level_A->GetVolume());
            });
    hebi_thread_->UpdateCounterweightVolume(ui_->tw_water_level_A->GetVolume());
#endif

    // MainWindow slots
    connect(hebi_thread_, &HebiThread::ErrorThrown,  // handle errors
            this, &MainWindow::HandleCriticalError);

    connect(hebi_thread_, &HebiThread::Connected,  // update UI
            this, &MainWindow::HandleHebiConnChanged);
    connect(hebi_thread_, &HebiThread::ReportFeedback,  // get feedback
            this, &MainWindow::HandleActuatorFeedback);
    connect(hebi_thread_, &HebiThread::ReportStatus,  // get minor statuses
            this, &MainWindow::HandleActuatorStatus);

#if LIBRA_VERSION == 2
    connect(hebi_thread_, &HebiThread::MotionModeChanged,  // sync mode toggle
            this, &MainWindow::HandleMotionModeChanged);
    connect(hebi_thread_, &HebiThread::FreeModeChanged,  // sync free toggle
            this, &MainWindow::HandleFreeModeChanged);
    connect(hebi_thread_, &HebiThread::MovementStateChanged,  // lock mode UI
            this, &MainWindow::HandleMovementStateChanged);
    connect(hebi_thread_, &HebiThread::CalibrationFinished,  // calibrated
            this, &MainWindow::HandleCalibrationFinished);
    connect(hebi_thread_, &HebiThread::CalibrationLoaded,  // loaded from file
            this, &MainWindow::HandleCalibrationLoaded);
#endif

    // ArduinoManager slots
    connect(hebi_thread_, &HebiThread::ReportArmTorque,  // update water command
            water_controller_, &WaterController::UpdateTorqueFeedback);
#if LIBRA_VERSION == 1
    connect(hebi_thread_, &HebiThread::InformPitch,  // update manip correction
            manip_controller_, &ManipController::UpdatePitchFeedback);
#endif

    // Thread cleanup
    connect(hebi_thread_, &HebiThread::finished,      // when thread exits,
            hebi_thread_, &HebiThread::deleteLater);  // deallocate

    hebi_thread_->start();

    // ========== EPOS Thread ==========

#if LIBRA_VERSION == 2
    epos_thread_ = new EposThread(this, debug_mode_);

    // MainWindow signals
    connect(this, &MainWindow::EnableDebugMode,  // update debug mode
            epos_thread_, &EposThread::SetDebugMode);

    connect(this, &MainWindow::ConnectEpos,  // connect to EPOS
            epos_thread_, &EposThread::Connect);
    connect(ui_->a_epos_disconnect, &QAction::triggered,  // disconnect EPOS
            epos_thread_, &EposThread::Disconnect);

    connect(this, &MainWindow::CommandEpos,  // update EPOS target(s)
            epos_thread_, &EposThread::SetTarget);
    connect(ui_->pb_arm_stop, &QPushButton::clicked,  // stop ALL actuators
            epos_thread_, &EposThread::Stop);

    // MainWindow slots
    connect(epos_thread_, &EposThread::ErrorThrown,  // handle errors
            this, &MainWindow::HandleCriticalError);

    connect(epos_thread_, &EposThread::Connected,  // update UI
            this, &MainWindow::HandleEposConnChanged);
    connect(epos_thread_, &EposThread::ReportFeedback,  // get feedback
            this, &MainWindow::HandleActuatorFeedback);
    connect(epos_thread_, &EposThread::ReportStatus,  // get minor statuses
            this, &MainWindow::HandleActuatorStatus);

    // Thread cleanup
    connect(epos_thread_, &EposThread::finished,      // when thread exits,
            epos_thread_, &EposThread::deleteLater);  // deallocate

    epos_thread_->start();
#endif
}

