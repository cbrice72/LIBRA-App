/**
 * @brief Standard constructor.
 *
 * @param parent Owning Qt widget
 */
MainWindow::MainWindow(QWidget* parent)
    : QMainWindow(parent), ui_(new Ui::MainWindow) {
    ui_->setupUi(this);
    default_size_ = this->size();  // for "Reset window size"

    logger_ = std::make_unique<QtLogger>("main_window", debug_mode_);
    logger_->Debug("Initializing MainWindow");

    // Runtime checks
    util::IsWslEnvironment();  // only warns, no action needed

    // Member initialization
    last_command_.resize(Actuator::kUndefined);

    // GUI configuration
    ConfigureUi();
    InitializeElementMaps();
    InitializeDeviceManagers();
    InitializeThreads();

    // Component auto-connect
    auto reply = QMessageBox::question(nullptr, "LIBRA App Startup",
                                       "Automatically connect all components?",
                                       QMessageBox::Yes | QMessageBox::No);
    if (reply == QMessageBox::Yes) {
        ui_->a_connect_all->trigger();
    } else {
        // Even if auto-connect was refused, some UI elements should be populated
        ui_->a_refresh_camera_list->trigger();
    }
}

/**
 * @brief Standard destructor.
 */
MainWindow::~MainWindow() {
    // Define a lambda for gracefully wrapping up worker thread(s)
    auto StopThread = [](QThread* thread) {
        if (thread != nullptr && thread->isRunning()) {
            thread->requestInterruption();  // signal thread to stop looping
            thread->wait();                 // wait for thread cleanup to finish
        }
    };

    // Cleanup
    StopThread(hebi_thread_);
#if LIBRA_VERSION == 2
    StopThread(epos_thread_);
#endif

    delete ui_;

    logger_->Debug("Cleaned up MainWindow");
}

