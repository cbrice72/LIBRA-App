/**
 * @brief One value per HEBI-controlled joint, in joint space, indexed by
 *        `Joint::Name`.
 */
using JointValues = std::vector<double>;

/**
 * @brief How the actuator of one joint should be commanded this cycle.
 */
enum class CommandMode : uint8_t {
    // Send the position/velocity command (trajectory or hold) plus the effort
    // feedforward, if any
    kPositionControl,

    // Send NO position/velocity command; only the effort feedforward, if any
    kEffortOnly
};

/**
 * @brief What the motion controller needs each cycle: measurements plus the
 *        reference commanded in the PREVIOUS cycle.
 */
struct MotionState {
    double dt{0.0};  // time since last cycle (s)

    // Measured
    JointValues pos;              // θ (rad)
    JointValues vel;              // θ̇ (rad/s)
    JointValues torque_actuator;  // torque applied by actuator (Nm)

    // Commanded in previous cycle ("cmd_vel", "cmd_acc"); needed before this
    // cycle's trajectory is evaluated
    JointValues ref_vel;  // θ̇_ref (rad/s)
    JointValues ref_acc;  // θ̈_ref (rad/s²)

    bool trajectory_active{false};  // a trajectory is being followed
};

/**
 * @brief What the motion controller wants done with the actuators this cycle.
 */
struct MotionCommand {
    explicit MotionCommand(const std::size_t& n_joints = 0)
        : mode(n_joints, CommandMode::kPositionControl),
          torque_actuator_cmd(n_joints) {}

    std::vector<CommandMode> mode;

    // Effort feedforward per joint (Nm), not clamped; none = don't send one
    std::vector<std::optional<double>> torque_actuator_cmd;

    // Trajectory clock rate: 1 = normal, 0.5 = slow, 0 = paused
    double playback_rate{1.0};
};

std::string MotionFormat(const double& value);

