/**
 * @brief CW gravity moment, m_cw·r_P (kg·m), as a function of CW mass.
 *
 * @note r_P (pitch pivot to CW pivot P) is linear in volume, so the moment is
 *       quadratic in m_cw and inverts exactly (no lookup table):
 *         r_P(V) = A + B·V
 */
class CwModel {
  public:
    explicit CwModel(const double& cw_pivot_dist_m,
                     const double& cw_pivot_slope_m_per_l,
                     const double& capacity_l);

    [[nodiscard]] bool IsValid() const {
        return error_.empty();
    }

    [[nodiscard]] const std::string& GetError() const {
        return error_;
    }

    [[nodiscard]] double GetCapacityMass() const;

    [[nodiscard]] double Moment(const double& mass_kg) const;
    [[nodiscard]] double MassForMoment(const double& moment,
                                       bool* clamped = nullptr) const;

  private:
    [[nodiscard]] double PivotDist(const double& volume_l) const;

    double r_P_0_{0.0};    // r_P at 0 L, A (m)
    double dr_P_dV_{0.0};  // change in r_P per liter, B (m/L)
    double capacity_l_;
    std::string error_;
};

