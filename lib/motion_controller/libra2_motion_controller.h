/**
 * @brief CW gravity moments, inertia, and their inverses as functions of CW
 *        mass.
 *
 * @note r_P (pitch joint O to CW pivot P, along the arm) is linear in volume,
 *       so the moment is quadratic in m_cw and inverts exactly (no lookup
 *       table). The hang points sit q_P from O, normal to the arm:
 *         r_P(V) = A + B·V
 */
class CwModel {
  public:
    explicit CwModel(const double& cw_pivot_dist, const double& cw_pivot_slope,
                     const double& cw_hang_offset, const double& capacity);

    [[nodiscard]] bool IsValid() const {
        return error_.empty();
    }

    [[nodiscard]] const std::string& GetError() const {
        return error_;
    }

    [[nodiscard]] CwModelParams GetParams() const;
    [[nodiscard]] double GetCapacityMass() const;

    [[nodiscard]] double Moment(const double& mass) const;
    [[nodiscard]] double HangMoment(const double& mass) const;
    [[nodiscard]] double EffectiveMoment(const double& mass,
                                         const double& theta) const;
    [[nodiscard]] std::optional<double> MassForMoment(
        const double& moment, const double& theta,
        bool* clamped = nullptr) const;

    [[nodiscard]] double Inertia(const double& mass) const;
    [[nodiscard]] double InertiaSlope(const double& mass) const;

  private:
    [[nodiscard]] double PivotDist(const double& volume) const;

    double r_P_0_{0.0};    // r_P at 0 L, A (m)
    double dr_P_dV_{0.0};  // change in r_P per liter, B (m/L)
    double q_P_{0.0};      // hang-point offset normal to arm, from O (m)
    double capacity_;      // CW capacity (L)
    std::string error_;
};

