  public:
    void Reset();
    std::optional<RestSample> Add(const double& dt, const double& pos,
                                  const double& vel,
                                  const double& torque_actuator,
                                  const bool& trajectory_active,
                                  const std::optional<double>& volume);

  private:
    int count_{0};
    double t_elapsed_s_{0.0};  // seconds
