/**
 * @brief LIBRA-II pitch motion controller: gravity feedforward, automatic
 *        torque compensation, CW-primary mode, and arm model and friction
 *        calibrations.
 *
 * @note The equations (Eq. NN) are derived in the JPGs in
 *       `LIBRA Archive/2026-10-02 LIBRA-II Controller Equations/`:
 *         - `A-B_Geometry_Gravity-Torques`  Eqs. 1-8
 *         - `C_Hanging-Counterweight`       Eqs. 9-14
 *         - `D-E_Joint-Dynamics_Balance`    Eqs. 15-21
 *         - `F_Stability`                   Eqs. 22-27
 *         - `G_Estimating-State`            Eqs. 28-33
 *         - `H_Holding-Torque-at-any-Angle` Eqs. 34-36
 *         - `I_Controller`                  Eqs. 37-40
 *       `I_Controller-Code-Equivalencies` maps their symbols to the variables
 *       and functions here, and `-_Free-Body-Diagram` defines the system.
 *
 * @note Code-specific: the pitch joint O sits above the arm/CW centerline the
 *       notebook pivots on (see `kPitchJointHeight`), so the CW hang points are
 *       q_P from O and the CW torque gains a q_P·sin θ term.
 */
