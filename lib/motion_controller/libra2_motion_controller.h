/******************************************************************************
 * @file   libra2_motion_controller.h
 * @brief  LIBRA-II pitch motion controller (holding + active); header file.
 *
 * @note   Equation numbers (Eq. ##) refer to the notebook scans in
 *         `LIBRA Archive/2026-10-02 LIBRA-II Controller Equations/`.
 *         All values are in joint space: positive pitch = arm up (CCW), and
 *         `torque_actuator` is the actuator's feedforward torque.
 *
 * @note   There are two ways to move the pitch joint (`MotionMode`):
 *           Tandem     - Actuator follows trajectory with feedforward torque
 *                        while CW fills/drains toward its target mass; torque
 *                        limits throttle actuator trajectory.
 *           CW Primary - Actuator is allowed to spin freely and CW alone moves
 *                        the arm until it reaches either target mass or angle
 *                        within tolerance of target, whichever comes first.
 *                        Actuator then takes over and holds position.
 *
 * @author Christian Brice
 * @todo   Generated by Claude, needs review.
 ******************************************************************************/

