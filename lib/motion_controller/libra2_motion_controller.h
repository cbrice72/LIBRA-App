    std::vector<RestSample> arm_samples_;  // raw samples behind arm model

    std::optional<FrictionResult> friction_result_;  // last measured/loaded

    // Inputs from slots
    std::optional<double> cw_vol_;   // V (L)
    std::optional<double> cw_mass_;  // m_cw (kg); Eq. 28, refreshed each cycle
    double cw_flow_{0.0};            // V̇ (L/s); 0 if unknown

    // Dynamics (Eq. 15), refreshed each cycle since the CW's share changes
    double inertia_{0.0};       // arm + CW inertia (kg·m²)
    double inertia_rate_{0.0};  // inertia rate (kg·m²/s), from CW flow
    bool inertia_ff_en_{true};  // off = inertia terms left out of Eq. 37

    // Mode and CW-primary state
    MotionMode mode_{MotionMode::kTandem};
    CwPhase cw_phase_{CwPhase::kIdle};
    bool cw_assist_done_{false};     // hand-off done; predictive CW off
