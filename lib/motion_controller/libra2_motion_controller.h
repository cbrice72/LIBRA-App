  public:
    explicit Libra2MotionController(Logger& logger, const double& cw_capacity);
    explicit Libra2MotionController(Logger& logger, const double& cw_pivot_dist,
                                    const double& cw_pivot_slope,
                                    const double& cw_hang_offset,
                                    const double& cw_capacity,
                                    const double& grav,
                                    const double& friction_coulomb,
                                    const double& friction_viscous,
                                    const double& arm_inertia);

    // --- Control Cycle ---

    Libra2Command Update(const MotionState& state);

    // --- Settings (all lock) ---

    bool SetMotionMode(const MotionMode& mode);
    [[nodiscard]] MotionMode GetMotionMode() const;

    [[nodiscard]] bool IsMoving() const;

    void SetCwVolume(const double& volume);
    void SetCwFlow(const double& flow);
    void EnableTorqueComp(const bool& enabled);
    void EnableInertiaFeedforward(const bool& enabled);
    bool SetTorqueCompBounds(const double& lower_bound,
                             const double& upper_bound);
    bool SetHandoffBand(const double& band);
    bool SetCwVolumeTolerance(const double& tolerance);

    // --- Arm Model ---

    void SetArmModel(const double& arm_level_torque,
                     const double& arm_hang_torque);
    void ClearArmModel();

    [[nodiscard]] bool IsCalibrated() const;

    [[nodiscard]] double GetArmLevelTorque() const;
    [[nodiscard]] double GetArmHangTorque() const;
    [[nodiscard]] double ComputeNetGravTorque(const double& theta,
                                              const double& cw_mass) const;

    // --- Calibration ---

    bool StartLevelCalibration();
    bool StartTwoAngleCalibration(const double& angle_a, const double& angle_b);
    bool StartFrictionCalibration(const double& angle_a, const double& angle_b,
                                  const double& max_speed);
    void CancelCalibration();
    [[nodiscard]] CalibrationStatus GetCalibrationStatus() const;
    [[nodiscard]] std::string GetCalibrationMessage() const;

    // --- Calibration Record ---

    [[nodiscard]] CalibrationRecord GetCalibrationRecord() const;
    bool LoadCalibrationRecord(const CalibrationRecord& record);

  protected:
    void OnTargetChanged() override;
    void OnStop() override;
    void OnReset() override;

  private:
    enum class CwPhase : uint8_t { kIdle, kCwMoving };

    struct AtcResult {
        double playback_rate{1.0};
        std::optional<CwCommand> cw_command;
    };

    /**
     * @brief State of a running friction calibration.
     */
    struct FrictionRun {
        double angle_lo{0.0};   // window start (rad)
        double angle_hi{0.0};   // window end (rad)
        double max_speed{0.0};  // caller's speed limit (rad/s)
        double volume{0.0};     // CW volume at start (L)
        std::size_t speed_idx{0};
        bool trajectory_seen{false};  // current sweep has started

        // Per-bin torque sums and counts for the current speed
        std::vector<double> up_sum;
        std::vector<double> down_sum;
        std::vector<int> up_count;
        std::vector<int> down_count;

        std::vector<FrictionPoint> points;
    };

    // --- Helper Functions ---

    AtcResult UpdateTorqueComp(const double& torque_magnitude,
                               const CwCommand& direction, const bool& braking);
    std::optional<CwCommand> PredictiveCwCommand(const double& theta_tgt,
                                                 const double& cw_mass,
                                                 double* cw_mass_tgt) const;
    bool RunCwPrimary(const double& theta, const double& theta_tgt,
                      Libra2Command& command);

    void ComputeDiagnostics(const double& theta,
                            const std::optional<double>& theta_tgt,
                            Libra2Diagnostics& diagnostics) const;

